/**
 * Writes supabase/seed.sql from the sample posts in lib/samplePosts.ts.
 * Run with: npx tsx scripts/make-seed.ts
 */
import { writeFileSync } from "node:fs";
import { samplePosts } from "../lib/samplePosts";
import { readingMinutes } from "../lib/content/doc";

const shorten = (s: string, n: number) =>
  s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n - 1)).replace(/[,.;:]$/, "") + "…";
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = samplePosts.map((p) =>
  [
    q(p.slug),
    q(p.title),
    q(p.excerpt),
    `${q(JSON.stringify(p.content))}::jsonb`,
    q(p.coverImage),
    q(p.coverAlt),
    `array[${p.tags.map(q).join(", ")}]::text[]`,
    q(shorten(p.excerpt, 160)),
    `'published'`,
    `${q(p.date + "T08:00:00Z")}::timestamptz`,
    String(readingMinutes(p.content)),
  ].join(",\n    "),
);

const sql = `-- Three sample posts, so the book has pages before you write your own.
-- Generated by scripts/make-seed.ts. Delete them from the admin area whenever you like.

insert into public.posts
  (slug, title, excerpt, content, cover_image_url, cover_image_alt, tags, seo_description, status, published_at, reading_minutes)
values
${rows.map((r) => `  (\n    ${r}\n  )`).join(",\n")}
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
